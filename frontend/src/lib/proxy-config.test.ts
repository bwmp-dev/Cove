import { expect, it } from "vitest";
import { validateProxyFileName } from "./proxy-config";

it("accepts only names the worker can manage", () => {
  expect(validateProxyFileName("legacy-import.yaml", [])).toBeNull();
  expect(validateProxyFileName("migrated_certificates.v2.yml", [])).toBeNull();
  for (const name of ["", "Legacy.yaml", "notes.toml", "../escape.yaml", ".hidden.yaml", "a b.yaml"]) {
    expect(validateProxyFileName(name, [])).not.toBeNull();
  }
  for (const name of ["routes.yaml", "panel.yaml", "cove-bridge.yaml"]) {
    expect(validateProxyFileName(name, [])).toMatch(/generated by Cove/);
  }
  expect(validateProxyFileName("extra.yaml", ["extra.yaml"])).toMatch(/already exists/);
});
