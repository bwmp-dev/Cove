import { useQuery } from "@tanstack/react-query";
import { Link } from "@tanstack/react-router";
import { BookOpen } from "lucide-react";
import { lazy, Suspense } from "react";
import { request } from "../api/client";
import { Breadcrumbs, Notice, PageHeader, QueryError, Section, Spinner } from "../components/ui";
import { buttonClass, linkClass } from "../lib/styles";

const specPath = "/api/v1/openapi.json";

// The renderer is large, so it loads only when someone opens the reference.
const ApiReference = lazy(() => import("../components/ApiReference").then((module) => ({ default: module.ApiReference })));

function Loading({ label }: { label: string }) {
  return (
    <div role="status" className="flex items-center gap-2 py-6 text-[13px] text-fg-muted">
      <Spinner /> {label}
    </div>
  );
}

export function ApiDocsPage() {
  const spec = useQuery({ queryKey: ["openapi"], queryFn: ({ signal }) => request<object>("GET", specPath, undefined, signal), staleTime: 5 * 60_000 });
  return (
    <>
      <PageHeader
        icon={<BookOpen aria-hidden />}
        title="API reference"
        description="Endpoints, permissions and schemas of the versioned Cove API, generated by this control plane."
        breadcrumbs={
          <Breadcrumbs>
            <Link to="/tokens" className="hover:text-fg">
              API keys and tokens
            </Link>
            API reference
          </Breadcrumbs>
        }
        actions={
          <a href={specPath} className={buttonClass()} download="cove-openapi.json">
            Download OpenAPI JSON
          </a>
        }
      />
      <div className="px-4 pt-5 sm:px-6">
        <Notice title="Try it out uses your signed-in session">
          Requests sent from this page run as you in the selected team and really change data. Clients outside the browser send a scoped API key as <span className="font-mono whitespace-nowrap">Authorization: Bearer</span>; each operation's <span className="font-mono whitespace-nowrap">x-cove-scope</span> names the permission it needs. Errors are returned as plain text.{" "}
          <Link to="/tokens" className={linkClass}>
            Create an API key
          </Link>
        </Notice>
      </div>
      <Section title="Endpoints">
        {spec.isPending && <Loading label="Loading API description" />}
        {spec.isError && <QueryError what="the API description" error={spec.error} onRetry={() => void spec.refetch()} retrying={spec.isFetching} />}
        {spec.data && (
          <Suspense fallback={<Loading label="Loading API reference" />}>
            <ApiReference spec={spec.data} />
          </Suspense>
        )}
      </Section>
    </>
  );
}
