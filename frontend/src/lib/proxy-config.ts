import type { ProxyChangeAction, ProxyChangeState, ProxyFileStatus, ProxyObjectStatus } from "../api/proxy";
import type { Tone } from "./nodes";

// Mirrors the worker's limits so obvious mistakes are caught before a round trip.
export const proxyFileLimit = 256 * 1024;
const fileName = /^[a-z0-9][a-z0-9_.-]{0,95}\.(?:yaml|yml)$/;

export function validateProxyFileName(name: string, existing: string[]): string | null {
  if (!name) return "Enter a file name.";
  if (!fileName.test(name)) return "Use lowercase letters, digits, dots, dashes or underscores, ending in .yaml or .yml.";
  if (name === "routes.yaml" || name === "panel.yaml" || name.startsWith("cove-")) return "routes.yaml, panel.yaml and cove- names are generated by Cove.";
  if (existing.includes(name)) return "A file with this name already exists.";
  return null;
}

export const fileStatuses: Record<ProxyFileStatus, { tone: Tone; label: string; description: string }> = {
  managed: { tone: "ok", label: "Managed", description: "Edited through Cove with validation and rollback." },
  unmanaged: { tone: "warn", label: "Not imported", description: "Already loaded by the proxy. Import it to edit or remove it through Cove." },
  protected: { tone: "neutral", label: "Generated", description: "Written by Cove for resource routes or the dashboard. Read-only." },
  unsupported: { tone: "neutral", label: "Unsupported", description: "Loaded by the proxy as is. Cove cannot manage this file." },
  missing: { tone: "bad", label: "Missing", description: "Cove manages this file, but it was removed outside Cove." },
};

export const objectStatuses: Record<ProxyObjectStatus, { tone: Tone; label: string }> = {
  enabled: { tone: "ok", label: "Enabled" },
  warning: { tone: "warn", label: "Warning" },
  disabled: { tone: "bad", label: "Disabled" },
  not_loaded: { tone: "bad", label: "Not loaded" },
  not_reported: { tone: "neutral", label: "Not reported" },
};

type NoticeTone = "info" | "warn" | "error" | "success";

export const changeStates: Record<ProxyChangeState, { tone: NoticeTone; label: string }> = {
  applying: { tone: "info", label: "Applying" },
  restoring: { tone: "warn", label: "Restoring the previous configuration" },
  succeeded: { tone: "success", label: "Applied" },
  failed: { tone: "error", label: "Failed" },
  interrupted: { tone: "warn", label: "Interrupted" },
  rejected: { tone: "error", label: "Rejected" },
  valid: { tone: "success", label: "Valid" },
  invalid: { tone: "error", label: "Not valid" },
};

const actionLabels: Record<ProxyChangeAction, string> = { put: "Save", delete: "Remove", import: "Import", validate: "Check" };

export function changeTitle(action: ProxyChangeAction, name: string, state: ProxyChangeState) {
  return `${actionLabels[action]} ${name}: ${changeStates[state]?.label ?? state}`;
}
